import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

export interface PdfCard {
  label: string;
  value: string;
  change: number | null;
  good: boolean | null;
}

const safe = (s: string) => s.replace(/[^\x20-\x7E\xA0-\xFF]/g, "?");

export async function buildReportPdf(input: {
  agencyName: string;
  clientName: string;
  periodLabel: string;
  cards: PdfCard[];
}): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`${safe(input.clientName)} - ${input.periodLabel} Ad Performance Report`);
  const page = doc.addPage([595, 842]);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const indigo = rgb(0.31, 0.27, 0.9);
  const ink = rgb(0.1, 0.12, 0.2);
  const muted = rgb(0.42, 0.45, 0.53);
  const { width, height } = page.getSize();

  page.drawRectangle({ x: 0, y: height - 130, width, height: 130, color: indigo });
  page.drawText(safe(input.agencyName).toUpperCase(), { x: 48, y: height - 55, size: 11, font: bold, color: rgb(0.85, 0.86, 1) });
  page.drawText("Monthly Ad Performance Report", { x: 48, y: height - 85, size: 22, font: bold, color: rgb(1, 1, 1) });
  page.drawText(`${safe(input.clientName)}  |  ${input.periodLabel}`, { x: 48, y: height - 110, size: 12, font, color: rgb(0.9, 0.9, 1) });

  const cardW = (width - 96 - 16) / 2;
  const cardH = 110;
  input.cards.forEach((c, i) => {
    const col = i % 2;
    const row = Math.floor(i / 2);
    const x = 48 + col * (cardW + 16);
    const y = height - 170 - cardH - row * (cardH + 16);
    page.drawRectangle({ x, y, width: cardW, height: cardH, color: rgb(0.97, 0.97, 1), borderColor: rgb(0.86, 0.87, 0.95), borderWidth: 1 });
    page.drawText(c.label, { x: x + 16, y: y + cardH - 28, size: 10, font: bold, color: muted });
    page.drawText(c.value, { x: x + 16, y: y + cardH - 64, size: 24, font: bold, color: ink });
    let txt = "No prior-month data";
    let color = muted;
    if (c.change !== null) {
      const sign = c.change > 0 ? "+" : "";
      txt = `${sign}${c.change.toFixed(1)}% vs. previous month`;
      if (c.good === true) color = rgb(0.06, 0.55, 0.32);
      else if (c.good === false) color = rgb(0.8, 0.18, 0.18);
    }
    page.drawText(txt, { x: x + 16, y: y + 18, size: 10, font, color });
  });

  page.drawText(`Generated by ReportPilot on ${new Date().toISOString().slice(0, 10)}`, { x: 48, y: 40, size: 9, font, color: muted });
  return doc.save();
}
